// 지속 영역(장판)의 **원소 타입**.
//
// 🔴 이 값의 역할은 "효과가 무엇인가"가 아니라 **중첩 성장을 가르는 기준**이다(정본 §10.5.2).
//    같은 타입끼리만 합쳐져 성장하고, 다른 타입은 겹쳐도 각자 유지된다.
//    실제 효과(데미지·둔화·지속시간)는 프리팹의 AreaZone 필드로 저작한다 — 타입별 하드코딩 금지.
//
// ⚠️ **축을 두 개 헷갈리지 말 것.** 폐기된 `FloorAreaEffect.AreaType{None,GrowOnOverlap,GrowOverTime}`
//    은 **성장 방식**이지 원소 타입이 아니었다. 이 enum 은 원소 타입 쪽이다.
//
// 🔴 값 추가는 끝에만. 프리팹에 정수로 직렬화된다.
public enum AreaZoneType
{
    Fire,       // 화염
    Swamp,      // 늪
    Poison,     // 독
    Lightning,  // 번개
}
