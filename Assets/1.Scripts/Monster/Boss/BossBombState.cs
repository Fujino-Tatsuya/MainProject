// 🔴 이걸 명시적으로 두지 않으면 반드시 엉킨다. 폭발 타이머와 되쳐내기 가능 여부가 상태에 묶이고,
//    **같은 콜라이더 쌍인데 상태에 따라 결과가 다르다**(투척 중 폭탄끼리 = 폭발 / 당구 중 = 서로 밀림).
//
// | 상태      | 물리                    | 폭발 타이머 | 되쳐내기 | 폭탄끼리 충돌      |
// |-----------|-------------------------|-------------|----------|--------------------|
// | Thrown    | 중력 on, Y 자유, 포물선 | 정지        | 불가     | 🔴 둘 다 폭발      |
// | Resting   | Y 고정, 정지            | **진행**    | **가능** | —                  |
// | Sliding   | Y 고정, 수평 직선       | 정지        | 불가     | 서로 밀림          |
// | Exploded  | —                       | —           | —        | AreaZone 스폰 후 despawn |
//
// ⚠️ 되쳐내기 가능 여부를 "속도가 0인가"로 판단하지 말 것 — 밀리다 순간적으로 느려지는 프레임에
//    맞으면 예외가 생긴다. **상태로 판단한다.**
public enum BossBombState
{
    Thrown = 0,  // 단계 1 — Wells 손에서 대각선 투척, 포물선
    Resting,     // 정지 — 폭발 타이머가 흐르고, 기본공격으로 되쳐낼 수 있다
    Sliding,     // 단계 2 — 바닥 위 수평 당구. 되쳐낸 쪽·맞은 쪽을 구분하지 않는다
    Exploded,    // 폭발 처리 완료(중복 폭발 가드)
}
